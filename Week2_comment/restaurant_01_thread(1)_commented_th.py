# อธิบาย: นำเข้าโมดูล threading เพื่อสร้างและควบคุม Thread ภายใน Process เดียว
import threading
# อธิบาย: นำเข้าฟังก์ชันจากโมดูล time ได้แก่ sleep, ctime, time สำหรับหน่วงเวลา ดูเวลา และวัดระยะเวลาการทำงาน
from time import sleep, ctime, time

# 1. ขั้นตอนต้อนรับหน้าร้าน ทำแบบ Synchronous เรียงทีละคน
# อธิบาย: ประกาศฟังก์ชันปกติสำหรับต้อนรับลูกค้า โดยรับพารามิเตอร์ customer
def greet_diners(customer):
    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"{ctime()} Greeting for Customer-{customer} ...")
    # อธิบาย: หยุดการทำงานของ Thread/Process ปัจจุบันประมาณ 1 วินาทีแบบ Blocking เพื่อจำลองเวลาที่ใช้ทำงาน
    sleep(1)
    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"{ctime()} Greeting for Customer-{customer} ...Done!")

# 2. กระบวนการส่วนตัวของลูกค้าแต่ละคน ที่จะถูกนำไปรันแยกในเธรดของตัวเอง
# อธิบาย: ประกาศฟังก์ชันสำหรับรวมขั้นตอนบริการของลูกค้าแต่ละคน โดยรับพารามิเตอร์ customer
def customer_private_workflow(customer):
    # Take Order
    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"{ctime()}  [Thread-{customer}] Taking Order ...")
    # อธิบาย: หยุดการทำงานของ Thread/Process ปัจจุบันประมาณ 1 วินาทีแบบ Blocking เพื่อจำลองเวลาที่ใช้ทำงาน
    sleep(1)
    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"{ctime()}  [Thread-{customer}] Taking Order ...Done!")

    # Do Cooking
    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"{ctime()}  [Thread-{customer}] Cooking Spaghetti ...")
    # อธิบาย: หยุดการทำงานของ Thread/Process ปัจจุบันประมาณ 1 วินาทีแบบ Blocking เพื่อจำลองเวลาที่ใช้ทำงาน
    sleep(1)
    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"{ctime()}  [Thread-{customer}] Cooking Spaghetti ...Done!")

    # Manage Bar
    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"{ctime()}  [Thread-{customer}] Manage Bar for Drink ...")
    # อธิบาย: หยุดการทำงานของ Thread/Process ปัจจุบันประมาณ 1 วินาทีแบบ Blocking เพื่อจำลองเวลาที่ใช้ทำงาน
    sleep(1)
    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"{ctime()}  [Thread-{customer}] Manage Bar for Drink ...Done!")
    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"{ctime()}  [Thread-{customer}] All served!\n")

# อธิบาย: ตรวจว่าไฟล์นี้ถูกสั่งรันโดยตรงหรือไม่ เพื่อให้โค้ดด้านในทำงานเฉพาะตอนรันไฟล์นี้
if __name__ == "__main__":
    # อธิบาย: สร้างลิสต์รายชื่อลูกค้าที่โปรแกรมจะนำมาจำลองการให้บริการ
    customers = ['A', 'B', 'C']
    # อธิบาย: บันทึกเวลาเริ่มต้นไว้ในตัวแปร start_time เพื่อนำไปคำนวณเวลาที่ใช้ทั้งหมด
    start_time = time()

    # ----------------------------------------------------
    # PHASE 1: Greet diners sequentially
    # ----------------------------------------------------
    # อธิบาย: วนลูปทีละคนตามรายชื่อลูกค้า เพื่อสร้างหรือเรียกขั้นตอนการทำงานสำหรับลูกค้าแต่ละคน
    for customer in customers:
        # อธิบาย: เรียกฟังก์ชันต้อนรับลูกค้าคนปัจจุบันและรอจนฟังก์ชันทำเสร็จ
        greet_diners(customer)

    # อธิบาย: แสดงข้อความสถานะการทำงานและข้อมูลที่เกี่ยวข้องออกทางหน้าจอ
    print(f"\n{ctime()} --- All customers greeted. Scheduling independent Threads! ---\n")

    # ----------------------------------------------------
    # PHASE 2: Spawn threads for concurrent phases
    # ----------------------------------------------------
    # อธิบาย: สร้างลิสต์ว่างสำหรับเก็บ Thread ของลูกค้าแต่ละคน
    customer_threads = []
    # อธิบาย: วนลูปทีละคนตามรายชื่อลูกค้า เพื่อสร้างหรือเรียกขั้นตอนการทำงานสำหรับลูกค้าแต่ละคน
    for customer in customers:
        # สร้างเธรดแยกให้ลูกค้าแต่ละคน
        # อธิบาย: สร้าง Thread ใหม่ โดยกำหนด customer_private_workflow เป็นงานหลักของ Thread และส่ง customer เป็นอาร์กิวเมนต์
        t = threading.Thread(target=customer_private_workflow, args=(customer,))
        # อธิบาย: เก็บ Thread ที่สร้างไว้ในลิสต์ เพื่อใช้รอทุก Thread ให้เสร็จภายหลัง
        customer_threads.append(t)
        # อธิบาย: สั่งให้ Thread นี้เริ่มทำงานจริง ทำให้หลาย Thread สามารถสลับกันทำงานได้
        t.start()

    # รอให้ลูกค้าทุกคนทำขั้นตอนทั้งหมดเสร็จสิ้น
    # อธิบาย: วนลูปผ่าน Thread ทุกตัว เพื่อรอให้แต่ละ Thread ทำงานเสร็จ
    for t in customer_threads:
        # อธิบาย: ให้ Main Thread รอจนกว่า Thread นี้จะทำงานเสร็จ
        t.join()

    # อธิบาย: คำนวณระยะเวลารวม โดยนำเวลาปัจจุบันลบด้วยเวลาเริ่มต้น
    duration = time() - start_time
    # อธิบาย: แสดงผลเวลารวม/สถานะสิ้นสุดของโปรแกรมออกทางหน้าจอ
    print(f"{ctime()} Finished Cooking in {duration:0.2f} seconds.")
