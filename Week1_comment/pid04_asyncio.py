# อธิบาย: นำเข้าฟังก์ชันเกี่ยวกับเวลาจากโมดูล time ได้แก่ ctime, time เพื่อใช้หน่วงเวลา แสดงเวลา หรือวัดเวลา
from time import ctime, time
# อธิบาย: นำเข้าโมดูล asyncio สำหรับเขียนโปรแกรมแบบ Asynchronous ด้วย Event Loop และ Task
import asyncio
# อธิบาย: นำเข้าโมดูล os เพื่อเรียกข้อมูลของระบบปฏิบัติการ เช่น Process ID (PID)
import os
# อธิบาย: นำเข้าโมดูล threading เพื่อสร้างและจัดการ Thread ภายใน Process เดียว
import threading

# อธิบาย: หมายเหตุเดิมของโค้ด: ฟังก์ชันของการทำงานแบบ Asynchronous
# ฟังก์ชันของการทำงานแบบ Asynchronous
# อธิบาย: ประกาศฟังก์ชันแบบ async ชื่อ make_coffee รับพารามิเตอร์ customer_name และสามารถใช้ await ภายในฟังก์ชันได้
async def make_coffee(customer_name):
    # อธิบาย: หมายเหตุเดิมของโค้ด: 1. Process ID และ Thread ID (จะเหมือนกันหมดเพราะรันใน Process/Thread เดียว)
    # 1. Process ID และ Thread ID (จะเหมือนกันหมดเพราะรันใน Process/Thread เดียว)
    # อธิบาย: อ่าน Process ID (PID) ของ Process ที่กำลังรันโค้ดบรรทัดนี้
    pid = os.getpid()
    # อธิบาย: อ่าน Native Thread ID ของ Thread ปัจจุบันจากระบบปฏิบัติการ
    thread_id = threading.current_thread().native_id

    # อธิบาย: หมายเหตุเดิมของโค้ด: 2. ดูข้อมูล Task ปัจจุบันของ asyncio
    # 2. ดูข้อมูล Task ปัจจุบันของ asyncio
    # อธิบาย: ดึง asyncio Task ที่กำลังรันฟังก์ชันนี้อยู่ในขณะปัจจุบัน
    current_task = asyncio.current_task()
    # อธิบาย: อ่านชื่อของ Task ปัจจุบัน เพื่อใช้แยก Task แต่ละงานตอนแสดงผล
    task_name = current_task.get_name()

    # อธิบาย: หมายเหตุเดิมของโค้ด: ใช้ id() เป็น Unique ID ของ Task
    # ใช้ id() เป็น Unique ID ของ Task
    # อธิบาย: ใช้ id() อ่านรหัสอ้างอิงเฉพาะของออบเจ็กต์ Task ปัจจุบัน
    task_id = id(current_task)

    # อธิบาย: แสดงข้อความสถานะและเวลาปัจจุบันทางหน้าจอ เพื่อให้เห็นลำดับและช่วงเวลาการทำงาน
    print(
        # อธิบาย: สร้างข้อความแบบ f-string โดยแทรกค่าตัวแปรลงในข้อความก่อนนำไปแสดงผล
        f"{ctime()} | [PID: {pid}] [TID: {thread_id}] "
        # อธิบาย: สร้างข้อความแบบ f-string โดยแทรกค่าตัวแปรลงในข้อความก่อนนำไปแสดงผล
        f"[Async Task ID: {task_id}] [Task Name: {task_name}] "
        # อธิบาย: สร้างข้อความแบบ f-string โดยแทรกค่าตัวแปรลงในข้อความก่อนนำไปแสดงผล
        f"กำลังชงกาแฟให้ ลูกค้า {customer_name}..."
    # อธิบาย: ปิดวงเล็บของคำสั่งหรือการเรียกฟังก์ชันแบบหลายบรรทัด
    )

    # อธิบาย: หมายเหตุเดิมของโค้ด: จุดที่ไม่ block thread
    # จุดที่ไม่ block thread
    # อธิบาย: พัก Task นี้เป็นเวลา 5 วินาทีแบบไม่บล็อก Thread ทำให้ Event Loop สามารถไปทำ Task อื่นระหว่างรอได้
    await asyncio.sleep(5)

    # อธิบาย: แสดงข้อความสถานะและเวลาปัจจุบันทางหน้าจอ เพื่อให้เห็นลำดับและช่วงเวลาการทำงาน
    print(
        # อธิบาย: สร้างข้อความแบบ f-string โดยแทรกค่าตัวแปรลงในข้อความก่อนนำไปแสดงผล
        f"{ctime()} | [PID: {pid}] [TID: {thread_id}] "
        # อธิบาย: สร้างข้อความแบบ f-string โดยแทรกค่าตัวแปรลงในข้อความก่อนนำไปแสดงผล
        f"[Async Task ID: {task_id}] [Task Name: {task_name}] "
        # อธิบาย: สร้างข้อความแบบ f-string โดยแทรกค่าตัวแปรลงในข้อความก่อนนำไปแสดงผล
        f"ลูกค้า {customer_name}: ได้รับกาแฟแล้ว!"
    # อธิบาย: ปิดวงเล็บของคำสั่งหรือการเรียกฟังก์ชันแบบหลายบรรทัด
    )

# อธิบาย: ประกาศฟังก์ชันแบบ async ชื่อ main รับพารามิเตอร์ ไม่มี และสามารถใช้ await ภายในฟังก์ชันได้
async def main():
    # อธิบาย: สร้างรายการคิวลูกค้า A, B, C เพื่อใช้วนทำงานกับลูกค้าแต่ละคน
    queue = ['A', 'B', 'C']

    # อธิบาย: เก็บ Process ID ของ Process หลักไว้ในตัวแปร main_pid
    main_pid = os.getpid()
    # อธิบาย: อ่าน Native Thread ID ของ Main Thread แล้วเก็บไว้ในตัวแปร main_tid
    main_tid = threading.current_thread().native_id

    # อธิบาย: แสดงข้อความสถานะและเวลาปัจจุบันทางหน้าจอ เพื่อให้เห็นลำดับและช่วงเวลาการทำงาน
    print(
        # อธิบาย: สร้างข้อความแบบ f-string โดยแทรกค่าตัวแปรลงในข้อความก่อนนำไปแสดงผล
        f"{ctime()} | [Main PID: {main_pid}] [Main TID: {main_tid}] "
        # อธิบาย: สร้างข้อความแบบ f-string โดยแทรกค่าตัวแปรลงในข้อความก่อนนำไปแสดงผล
        f"=== เริ่มระบบจำลองตู้กาแฟแบบ asyncio ==="
    # อธิบาย: ปิดวงเล็บของคำสั่งหรือการเรียกฟังก์ชันแบบหลายบรรทัด
    )

    # อธิบาย: บันทึกเวลาปัจจุบันก่อนเริ่มงาน เพื่อใช้คำนวณระยะเวลาทำงานทั้งหมดภายหลัง
    start_time = time()

    # อธิบาย: สร้างลิสต์ว่างสำหรับเก็บ asyncio Task ที่สร้างขึ้น
    tasks = []

    # อธิบาย: วนลูปนำสมาชิกแต่ละตัวจาก queue มาเก็บในตัวแปร customer แล้วทำคำสั่งภายในบล็อกทีละรอบ
    for customer in queue:
        # อธิบาย: หมายเหตุเดิมของโค้ด: สร้าง Coroutine
        # สร้าง Coroutine
        # อธิบาย: เรียกฟังก์ชัน async make_coffee() เพื่อสร้าง coroutine ของลูกค้าคนปัจจุบัน แต่ยังไม่เริ่มรันทันที
        coro = make_coffee(customer)

        # อธิบาย: หมายเหตุเดิมของโค้ด: แปลงเป็น Task ให้ Event Loop จัดการ
        # แปลงเป็น Task ให้ Event Loop จัดการ
        # อธิบาย: สร้าง asyncio Task จาก coroutine เพื่อให้ Event Loop สามารถจัดตารางให้รันแบบ concurrent ได้
        task = asyncio.create_task(
            # อธิบาย: ส่ง coroutine ที่สร้างไว้เป็นอาร์กิวเมนต์หลักให้ asyncio.create_task()
            coro,
            # อธิบาย: ตั้งชื่อ asyncio Task ตามลูกค้า เพื่อให้ระบุ Task ได้ง่ายตอนตรวจสอบการทำงาน
            name=f"Task-{customer}"
        # อธิบาย: ปิดวงเล็บของคำสั่งหรือการเรียกฟังก์ชันแบบหลายบรรทัด
        )

        # อธิบาย: เพิ่ม Task ที่สร้างแล้วเข้าไปในลิสต์ tasks เพื่อรอทุก Task พร้อมกันภายหลัง
        tasks.append(task)

    # อธิบาย: หมายเหตุเดิมของโค้ด: รอให้ทุก Task เสร็จพร้อมกัน
    # รอให้ทุก Task เสร็จพร้อมกัน
    # อธิบาย: รอให้ Task ทุกตัวในลิสต์ tasks ทำงานเสร็จ โดย Task เหล่านั้นสามารถสลับกันทำงานระหว่างจุด await ได้
    await asyncio.gather(*tasks)

    # อธิบาย: คำนวณเวลาที่ใช้ทั้งหมด โดยนำเวลาปัจจุบันลบด้วยเวลาเริ่มต้น
    duration = time() - start_time

    # อธิบาย: แสดงข้อความสถานะและเวลาปัจจุบันทางหน้าจอ เพื่อให้เห็นลำดับและช่วงเวลาการทำงาน
    print(f"{ctime()} | ใช้เวลารวมทั้งหมด: {duration:.2f} วินาที")

# อธิบาย: ตรวจว่าไฟล์นี้ถูกเรียกใช้งานโดยตรงหรือไม่ เพื่อให้โค้ดด้านล่างรันเฉพาะตอนเปิดไฟล์นี้โดยตรง
if __name__ == "__main__":
    # อธิบาย: สร้างและเปิด Event Loop แล้วรัน coroutine main() จนทำงานเสร็จ จากนั้นปิด Event Loop
    asyncio.run(main())
