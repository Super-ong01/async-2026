# อธิบาย: ประกาศฟังก์ชันชื่อ make_coffee รับพารามิเตอร์ customer_name สำหรับรวมขั้นตอนการทำงานไว้เป็นชุดเดียว
def make_coffee(customer_name):
    # อธิบาย: แสดงข้อความสถานะและเวลาปัจจุบันทางหน้าจอ เพื่อให้เห็นลำดับและช่วงเวลาการทำงาน
    print(f"{ctime()} | Making coffee for {customer_name}...")
    # อธิบาย: หยุดการทำงานของ Thread ปัจจุบันเป็นเวลา 1.0 วินาที เพื่อจำลองช่วงเวลาที่ต้องรอ
    sleep(1.0)
    # อธิบาย: แสดงข้อความสถานะและเวลาปัจจุบันทางหน้าจอ เพื่อให้เห็นลำดับและช่วงเวลาการทำงาน
    print(f"{ctime()} | Coffee ready for {customer_name}!")
    # อธิบาย: เรียกฟังก์ชันอัปเดตหมายเลข/สถานะบน LCD หลังทำกาแฟให้ลูกค้าคนนี้
    update_cup_number(customer_name)
    # อธิบาย: คำสั่งว่างชั่วคราว ทำให้บล็อกนี้ถูกต้องตามไวยากรณ์ Python แต่ยังไม่มีการทำงานจริง
    pass

# อธิบาย: ประกาศฟังก์ชันชื่อ main รับพารามิเตอร์ ไม่มี สำหรับรวมขั้นตอนการทำงานไว้เป็นชุดเดียว
def main():
    # อธิบาย: สร้างรายการคิวลูกค้า A, B, C เพื่อใช้วนทำงานกับลูกค้าแต่ละคน
    queue = ['A', 'B', 'C']

    # อธิบาย: แสดงข้อความสถานะและเวลาปัจจุบันทางหน้าจอ เพื่อให้เห็นลำดับและช่วงเวลาการทำงาน
    print(f"{ctime()} | === Multi-threading Coffee Machine ===")
    # อธิบาย: บันทึกเวลาปัจจุบันก่อนเริ่มงาน เพื่อใช้คำนวณระยะเวลาทำงานทั้งหมดภายหลัง
    start_time = time()

    # อธิบาย: สร้างลิสต์ว่างสำหรับเก็บออบเจ็กต์ Thread ที่สร้างขึ้น
    threads = []
    # อธิบาย: วนลูปนำสมาชิกแต่ละตัวจาก queue มาเก็บในตัวแปร customer แล้วทำคำสั่งภายในบล็อกทีละรอบ
    for customer in queue:
        # อธิบาย: สร้าง Thread ใหม่และกำหนดฟังก์ชันเป้าหมายที่จะให้ Thread นั้นทำงาน
        t = threading.Thread(target=make_coffee, args=(customer,))
        # อธิบาย: เพิ่ม Thread ที่สร้างแล้วเข้าไปในลิสต์ threads เพื่อเก็บไว้รอ join ภายหลัง
        threads.append(t)
        # อธิบาย: สั่งให้ Thread เริ่มทำงานจริง; ระบบปฏิบัติการจะเป็นผู้จัดตารางการทำงานของ Thread
        t.start()

    # อธิบาย: วนลูปนำสมาชิกแต่ละตัวจาก threads มาเก็บในตัวแปร t แล้วทำคำสั่งภายในบล็อกทีละรอบ
    for t in threads:
        # อธิบาย: ให้ Main Thread รอจนกว่า Thread นี้จะทำงานเสร็จ ก่อนดำเนินต่อไป
        t.join()

    # อธิบาย: คำนวณเวลาที่ใช้ทั้งหมด โดยนำเวลาปัจจุบันลบด้วยเวลาเริ่มต้น
    duration = time() - start_time
    # อธิบาย: แสดงข้อความสถานะและเวลาปัจจุบันทางหน้าจอ เพื่อให้เห็นลำดับและช่วงเวลาการทำงาน
    print(f"{ctime()} | Total time: {duration:.2f} seconds")
    # อธิบาย: คำสั่งว่างชั่วคราว ทำให้บล็อกนี้ถูกต้องตามไวยากรณ์ Python แต่ยังไม่มีการทำงานจริง
    pass

# อธิบาย: ตรวจว่าไฟล์นี้ถูกเรียกใช้งานโดยตรงหรือไม่ เพื่อให้โค้ดด้านล่างรันเฉพาะตอนเปิดไฟล์นี้โดยตรง
if __name__ == "__main__":
    # อธิบาย: เรียกฟังก์ชัน main() เพื่อเริ่มลำดับการทำงานหลักของโปรแกรม
    main()
