# อธิบาย: ประกาศฟังก์ชันหลักของโปรแกรม
def main():
    # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
    print(f"{ctime()} | Resetting every student's lights...")
    # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
    print(f"Total students: {len(STUDENT_IDS)}")

    # อธิบาย: บันทึกเวลาเริ่มต้นเพื่อใช้คำนวณเวลารวม
    start_time = time()
    # อธิบาย: คำสั่ง Python บรรทัดนี้เป็นส่วนหนึ่งของลำดับการทำงานของโปรแกรม
    success_count = 0
    # อธิบาย: คำสั่ง Python บรรทัดนี้เป็นส่วนหนึ่งของลำดับการทำงานของโปรแกรม
    error_count = 0

    # ส่งพร้อมกันสูงสุด 10 requests
    # อธิบาย: สร้าง Thread Pool สูงสุด 10 Thread เพื่อส่งคำขอรีเซ็ตหลายคนพร้อมกัน
    with ThreadPoolExecutor(max_workers=10) as executor:
        # อธิบาย: สร้าง Dictionary สำหรับเก็บ Future ของแต่ละงานและผูกกับ student_id
        futures = {
            # อธิบาย: ส่งฟังก์ชัน reset_student_lights เข้า Thread Pool เพื่อเริ่มทำงานใน Thread
            executor.submit(reset_student_lights, student_id): student_id
            # อธิบาย: คำสั่ง Python บรรทัดนี้เป็นส่วนหนึ่งของลำดับการทำงานของโปรแกรม
            for student_id in STUDENT_IDS
        # อธิบาย: ปิดโครงสร้างข้อมูลหรือคำสั่งหลายบรรทัดที่เริ่มไว้ก่อนหน้า
        }

        # อธิบาย: วนรับ Future ตามลำดับที่งานใดเสร็จก่อน โดยไม่ต้องรอตามลำดับเดิม
        for future in as_completed(futures):
            # อธิบาย: อ่านผลลัพธ์จาก Future ที่ทำงานเสร็จแล้ว
            result = future.result()
            # อธิบาย: อ่านรหัสนักศึกษาจากผลลัพธ์
            student_id = result["student_id"]

            # อธิบาย: ตรวจว่างานรีเซ็ตของนักศึกษาคนนี้สำเร็จหรือไม่
            if result["success"]:
                # อธิบาย: เพิ่มจำนวนงานที่สำเร็จขึ้น 1
                success_count += 1
                # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
                print(f"{ctime()} | {student_id} -> OFF ✅")
            # อธิบาย: ถ้าเงื่อนไขก่อนหน้าไม่เป็นจริง ให้ทำงานในส่วน else
            else:
                # อธิบาย: เพิ่มจำนวนงานที่ล้มเหลวขึ้น 1
                error_count += 1
                # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
                print(
                    # อธิบาย: คำสั่ง Python บรรทัดนี้เป็นส่วนหนึ่งของลำดับการทำงานของโปรแกรม
                    f"{ctime()} | {student_id} -> ERROR ❌ "
                    # อธิบาย: คำสั่ง Python บรรทัดนี้เป็นส่วนหนึ่งของลำดับการทำงานของโปรแกรม
                    f"{result['result']}"
                # อธิบาย: ปิดโครงสร้างข้อมูลหรือคำสั่งหลายบรรทัดที่เริ่มไว้ก่อนหน้า
                )

    # อธิบาย: คำนวณเวลารวมทั้งหมดตั้งแต่เริ่มโปรแกรม
    total_time = time() - start_time

    # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
    print("\n" + "=" * 50)
    # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
    print(f"Success : {success_count}")
    # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
    print(f"Errors  : {error_count}")
    # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
    print(f"Total   : {len(STUDENT_IDS)}")
    # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
    print(f"Time    : {total_time:.2f} seconds")
    # อธิบาย: แสดงข้อความสถานะหรือผลลัพธ์ออกทางหน้าจอ
    print("=" * 50)


